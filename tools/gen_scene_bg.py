import os
from PIL import Image

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
src = os.path.join(here, "scene-src")          # 放 6 张原始场景 PNG
out = os.path.join(root, "main", "scene_home_bg.c")

# name -> source file, comment
items = [
    ("scene_clear_bg",  "shiyie",  "PRTS 首页场景「视野」- 罗德岛顶层甲板, 晴日"),
    ("scene_cloudy_bg", "yinyun",  "PRTS 首页场景「阴云」- 雨雾之城"),
    ("scene_rain_bg",   "mihai",   "PRTS 首页场景「秘海」- 风雨海面"),
    ("scene_snow_bg",   "yandong", "PRTS 首页场景「严冬」- 风雪荒村"),
    ("scene_dusk_bg",   "shangye", "PRTS 首页场景「商业」- 暮色霓虹街景"),
    ("scene_night_bg",  "yemu",    "PRTS 首页场景「夜幕」- 罗德岛双月夜空"),
]

def to565(im):
    im = im.convert("RGB")
    w, h = im.size
    tw = int(h * 4 / 3)
    if tw <= w:
        x0 = (w - tw) // 2
        im = im.crop((x0, 0, x0 + tw, h))
    else:
        th = int(w * 3 / 4)
        y0 = (h - th) // 2
        im = im.crop((0, y0, w, y0 + th))
    im = im.resize((320, 240), Image.LANCZOS)
    px = im.load()
    buf = bytearray()
    for y in range(240):
        for x in range(320):
            r, g, b = px[x, y]
            v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
            buf.append(v & 0xFF)
            buf.append((v >> 8) & 0xFF)
    return bytes(buf)

lines = []
lines.append('#include "lvgl.h"')
lines.append('')
lines.append('/*')
lines.append(' * Home scenery backgrounds, cropped to 320x240 RGB565.')
lines.append(' * Source: PRTS wiki "首页场景一览" (https://prts.wiki/w/首页场景一览),')
lines.append(' * the in-game home screen scenes.  Generated by _scene/gen_bg.py.')
lines.append(' */')
lines.append('')
lines.append('#if LV_COLOR_DEPTH != 16 || LV_COLOR_16_SWAP != 0')
lines.append('#error "Home scenery expects RGB565 with LV_COLOR_16_SWAP=0"')
lines.append('#endif')
lines.append('')
lines.append('#ifndef LV_ATTRIBUTE_MEM_ALIGN')
lines.append('#define LV_ATTRIBUTE_MEM_ALIGN')
lines.append('#endif')
lines.append('#ifndef LV_ATTRIBUTE_LARGE_CONST')
lines.append('#define LV_ATTRIBUTE_LARGE_CONST')
lines.append('#endif')
lines.append('')

total = 0
for name, fname, desc in items:
    p = os.path.join(src, fname + ".png")
    data = to565(Image.open(p))
    total += len(data)
    lines.append('/* %s (%d bytes) */' % (desc, len(data)))
    lines.append('static const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_LARGE_CONST uint8_t %s_map[] = {' % name)
    for i in range(0, len(data), 24):
        chunk = data[i:i+24]
        lines.append(','.join('0x%02x' % b for b in chunk) + ',')
    lines.append('};')
    lines.append('const lv_img_dsc_t %s = {' % name)
    lines.append(' .header.cf = LV_IMG_CF_TRUE_COLOR,')
    lines.append(' .header.always_zero = 0,')
    lines.append(' .header.reserved = 0,')
    lines.append(' .header.w = 320,')
    lines.append(' .header.h = 240,')
    lines.append(' .data_size = sizeof(%s_map),' % name)
    lines.append(' .data = %s_map,' % name)
    lines.append('};')
    lines.append('')

with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines))
print("wrote", out, os.path.getsize(out), "bytes, image data", total)
